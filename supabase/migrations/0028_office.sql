-- 0028: "maktab al-ustool" virtual AI office (owner request after a video of an AI company with 15 AI employees).
--  * office_tasks: one row per task given to an AI "employee" (agent). Statuses: new, working, needs_you, done, rejected.
--    The owner approves or rejects tasks in needs_you from the site (office_decide). Nothing runs without that approval.
--  * office_reports: the 8 AM daily brief and the weekly "library" review, written by Claude (service role).
--  * Browser access: read with 'view'; add a task with office_add_task ('create'); decide/archive with is_admin().
--    No delete anywhere: archive = is_active false.
-- No existing table, column or row changes. ASCII only. Safe to run more than once.
-- =====================================================================
create table if not exists office_tasks (
  id            uuid primary key default gen_random_uuid(),
  task_no       bigint generated by default as identity,
  agent         text not null check (agent in ('manager','maintenance','excel','custody','docs','oil','reports','food')),
  title         text not null,
  details       text,
  status        text not null default 'new' check (status in ('new','working','needs_you','done','rejected')),
  needs_note    text,
  decision      text check (decision in ('approved','rejected')),
  decision_note text,
  decided_by    uuid,
  decided_at    timestamptz,
  result        text,
  source        text not null default 'site',
  created_by    uuid default auth.uid(),
  created_at    timestamptz not null default now(),
  updated_at    timestamptz not null default now(),
  done_at       timestamptz,
  is_active     boolean not null default true
);
create index if not exists office_tasks_agent_idx on office_tasks(agent, status);
alter table office_tasks enable row level security;
revoke all on office_tasks from anon, public;
revoke insert, update, delete, truncate, references, trigger on office_tasks from authenticated;
grant select on office_tasks to authenticated;
do $$ begin
  if not exists (select 1 from pg_policies where schemaname = 'public' and tablename = 'office_tasks' and policyname = 'p_select') then
    create policy p_select on office_tasks for select to authenticated using (has_perm('view'));
  end if;
end $$;

create table if not exists office_reports (
  id          uuid primary key default gen_random_uuid(),
  kind        text not null check (kind in ('daily','weekly')),
  report_date date not null,
  title       text,
  body        jsonb not null default '{}'::jsonb,
  created_at  timestamptz not null default now(),
  unique (kind, report_date)
);
alter table office_reports enable row level security;
revoke all on office_reports from anon, public;
revoke insert, update, delete, truncate, references, trigger on office_reports from authenticated;
grant select on office_reports to authenticated;
do $$ begin
  if not exists (select 1 from pg_policies where schemaname = 'public' and tablename = 'office_reports' and policyname = 'p_select') then
    create policy p_select on office_reports for select to authenticated using (has_perm('view'));
  end if;
end $$;

create or replace function office_add_task(p_agent text, p_title text, p_details text default null)
returns office_tasks language plpgsql security definer set search_path = public as $$
declare r office_tasks;
begin
  if not (is_admin() or has_perm('create')) then raise exception 'PERMISSION_DENIED' using errcode = '42501'; end if;
  if coalesce(trim(p_title), '') = '' then raise exception 'TITLE_REQUIRED'; end if;
  insert into office_tasks (agent, title, details) values (coalesce(nullif(p_agent, ''), 'manager'), trim(p_title), nullif(trim(p_details), ''))
  returning * into r;
  return r;
end $$;

create or replace function office_decide(p_id uuid, p_decision text, p_note text default null)
returns office_tasks language plpgsql security definer set search_path = public as $$
declare r office_tasks;
begin
  if not is_admin() then raise exception 'PERMISSION_DENIED' using errcode = '42501'; end if;
  if p_decision not in ('approved','rejected') then raise exception 'BAD_DECISION'; end if;
  update office_tasks set decision = p_decision, decision_note = nullif(trim(p_note), ''), decided_by = auth.uid(), decided_at = now(),
         status = case when p_decision = 'approved' then 'working' else 'rejected' end, updated_at = now()
   where id = p_id and is_active and status = 'needs_you'
  returning * into r;
  if r.id is null then raise exception 'NOT_WAITING'; end if;
  return r;
end $$;

create or replace function office_archive_task(p_id uuid)
returns office_tasks language plpgsql security definer set search_path = public as $$
declare r office_tasks;
begin
  if not is_admin() then raise exception 'PERMISSION_DENIED' using errcode = '42501'; end if;
  update office_tasks set is_active = false, updated_at = now() where id = p_id returning * into r;
  return r;
end $$;

revoke execute on function office_add_task(text, text, text) from public, anon;
revoke execute on function office_decide(uuid, text, text) from public, anon;
revoke execute on function office_archive_task(uuid) from public, anon;
grant execute on function office_add_task(text, text, text) to authenticated;
grant execute on function office_decide(uuid, text, text) to authenticated;
grant execute on function office_archive_task(uuid) to authenticated;

